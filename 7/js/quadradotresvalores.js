function quadradotresvalores(){
    let valor1 = parseInt(prompt("Digite o primeiro valor:"))
    let valor2 = parseInt(prompt("Insira segundo segundo valor: "))
    let valor3 = parseInt(prompt("Insira terceiro terceiro valor: "))
    let somatodos1 = valor1 ** 2
    let somatodos2 = valor2 ** 2
    let somatodos3 = valor3 ** 2
    let resultado = somatodos1 + somatodos2 + somatodos3
    alert(`O resultado da soma dos quadrados dos valores é: ${resultado}.`)

}