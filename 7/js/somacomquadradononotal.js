function somacomquadradonotal(){
    let valor1 = parseInt(prompt("Digite o primeiro valor:"))
    let valor2 = parseInt(prompt("Digite o segundo valor:"))
    let valor3 = parseInt(prompt("Digite o terceiro valor: "))
    let resultado = valor1 + valor2 + valor3
    let quadrado = resultado ** 2
    alert(`O resultado da soma dos valores é: ${resultado}.`)
    alert(`O quadrado do resultado da soma dos valores é: ${quadrado}.`)
}
